// android home-screen widgets for twilight (expo-widgets 58).
// the public "expo-widgets" plugin is run-once and also drives the ios widget
// extension, so the existing bare entry keeps doing that (ios live activity)
// and this entry runs only its android half, plus:
// - providers that hand "open" / "sleep:start" / "sleep:stop" button presses
//   to modules/twilight-widget-actions, which opens the app with a pending
//   action (glance buttons can only broadcast; the app performs the action,
//   so it works from a cold start like swift's openAppWhenRun intents)
// - the widget drawables (night-sky / sunset backgrounds, icons, previews)
// - picker preview images and a night-sky loading layout in each widget's
//   appwidget-provider xml
const fs = require('fs');
const path = require('path');
const { AndroidConfig, withDangerousMod } = require('expo/config-plugins');
const withAndroidWidgets = require('expo-widgets/plugin/build/android/withAndroidWidgets').default;
const {
  getProviderClassName,
  getWidgetInfoResourceName,
} = require('expo-widgets/plugin/build/android/resourceNames');

const { RADIUS, SKY_GRADIENTS, skyDrawableXml } = require('./sky.cjs');

const RES_DIR = path.join(__dirname, 'res');

function providerKt(androidPackage, widget) {
  return `package ${androidPackage}

import android.content.Context
import android.content.Intent
import expo.modules.twilightwidgetactions.TwilightWidgetActions
import expo.modules.widgets.ExpoWidgetsAppWidgetProvider

// generated by plugins/android-widgets (replaces the expo-widgets provider):
// open / sleep:start / sleep:stop buttons go to modules/twilight-widget-actions
class ${getProviderClassName(widget)} : ExpoWidgetsAppWidgetProvider(${JSON.stringify(widget.name)}) {
  override fun onReceive(context: Context, intent: Intent) {
    if (TwilightWidgetActions.handle(context, intent)) return
    super.onReceive(context, intent)
  }
}
`;
}

function copyDir(from, to) {
  fs.mkdirSync(to, { recursive: true });
  for (const entry of fs.readdirSync(from, { withFileTypes: true })) {
    const source = path.join(from, entry.name);
    const target = path.join(to, entry.name);
    if (entry.isDirectory()) copyDir(source, target);
    else fs.copyFileSync(source, target);
  }
}

function writeSkies(resDir) {
  for (const [folder, radius] of [
    ['drawable', RADIUS.base],
    ['drawable-v31', RADIUS.v31],
  ]) {
    fs.mkdirSync(path.join(resDir, folder), { recursive: true });
    for (const [name, sky] of Object.entries(SKY_GRADIENTS)) {
      fs.writeFileSync(path.join(resDir, folder, `${name}.xml`), skyDrawableXml(sky, radius));
      // starless variant for layouts whose text crosses the star field
      fs.writeFileSync(
        path.join(resDir, folder, `${name}_plain.xml`),
        skyDrawableXml({ ...sky, stars: false }, radius)
      );
    }
  }
}

// picker preview + a night-sky loading layout instead of expo's text placeholder
function patchWidgetInfo(infoPath, previewImage) {
  let xml = fs.readFileSync(infoPath, 'utf8');
  xml = xml.replace('@layout/expo_widgets_initial_layout', '@layout/twilight_widget_loading');
  if (previewImage && !xml.includes('android:previewImage')) {
    const ns = 'xmlns:android="http://schemas.android.com/apk/res/android"';
    xml = xml.replace(ns, `${ns}\n  android:previewImage="@drawable/${previewImage}"`);
  }
  fs.writeFileSync(infoPath, xml);
}

function withTwilightWidgetFiles(config, widgets) {
  return withDangerousMod(config, [
    'android',
    async (config) => {
      const androidPackage = AndroidConfig.Package.getPackage(config);
      if (!androidPackage) throw new Error('plugins/android-widgets needs android.package in app.json');
      const mainDir = path.join(config.modRequest.platformProjectRoot, 'app/src/main');
      const javaDir = path.join(mainDir, 'java', ...androidPackage.split('.'));
      const resDir = path.join(mainDir, 'res');
      fs.mkdirSync(javaDir, { recursive: true });
      copyDir(RES_DIR, resDir);
      writeSkies(resDir);
      for (const widget of widgets) {
        fs.writeFileSync(path.join(javaDir, `${getProviderClassName(widget)}.kt`), providerKt(androidPackage, widget));
        patchWidgetInfo(
          path.join(resDir, 'xml', `${getWidgetInfoResourceName(widget)}.xml`),
          widget.android?.previewImage
        );
      }
      return config;
    },
  ]);
}

module.exports = function withTwilightAndroidWidgets(config, props = {}) {
  const widgets = (props.widgets ?? []).filter((widget) => widget.android !== null);
  // registered before expo-widgets' mods on purpose: the newest mod runs
  // first, so these files are written after (and replace) the generated ones
  config = withTwilightWidgetFiles(config, widgets);
  return withAndroidWidgets(config, { ...props, widgets: props.widgets ?? [] });
};
