// widget background drawables, one per theme plus the active-session tint.
// gradients mirror src/theme/palettes.ts backgroundGradientStart/End (top to
// bottom, like the app's Screen background); a unit test keeps them in sync.
// the active sky is swift's ProfileControlWidget green container, deepened so
// white text stays readable.
const SKY_GRADIENTS = {
  twilight_widget_sky_twilight: { top: '#0a1520', bottom: '#0f2a3d', stars: true },
  twilight_widget_sky_amethyst: { top: '#0c1445', bottom: '#2c1e5e', stars: true },
  twilight_widget_sky_sunset: { top: '#ff9966', bottom: '#ff5e62', stars: false },
  twilight_widget_sky_active: { top: '#2fb855', bottom: '#1c8a3e', stars: false },
};

// launcher corner radius: fixed before android 12, the system value after
const RADIUS = { base: '24dp', v31: '@android:dimen/system_app_widget_background_radius' };

function skyDrawableXml(sky, radius) {
  const stars = sky.stars
    ? `
  <item
    android:gravity="top|center_horizontal"
    android:width="132dp"
    android:height="36dp"
    android:top="2dp"
        android:drawable="@drawable/twilight_widget_stars" />`
    : '';
  return `<?xml version="1.0" encoding="utf-8"?>
<!-- generated by plugins/android-widgets: edit sky.cjs instead -->
<layer-list xmlns:android="http://schemas.android.com/apk/res/android">
  <item>
    <shape android:shape="rectangle">
      <gradient android:angle="270" android:startColor="${sky.top}" android:endColor="${sky.bottom}" />
      <corners android:radius="${radius}" />
    </shape>
  </item>${stars}
</layer-list>
`;
}

module.exports = { SKY_GRADIENTS, RADIUS, skyDrawableXml };
